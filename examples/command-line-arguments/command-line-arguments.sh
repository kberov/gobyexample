# За придобиване на опит с податките на командния ред, най-добре е първо да
# изградите програмата като изпълните `go build`.
$ go build command-line-arguments.go
$ ./command-line-arguments a b c d
[./command-line-arguments a b c d]       
[a b c d]
c

